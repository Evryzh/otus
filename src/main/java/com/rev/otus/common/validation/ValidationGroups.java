package com.rev.otus.common.validation;

/**
 * Группы валидации для CRUD операций.
 *
 * <p>Используются в DTO для применения разных правил валидации
 * в зависимости от HTTP-метода:
 * <ul>
 *   <li>{@link OnCreate} — POST (создание)</li>
 *   <li>{@link OnPut} — PUT (полное обновление)</li>
 *   <li>{@link OnPatch} — PATCH (частичное обновление)</li>
 * </ul>
 */
public interface ValidationGroups {

    /**
     * Группа валидации для операции создания (POST).
     *
     * <p>Особенности:
     * <ul>
     *   <li>Все обязательные поля должны быть заполнены ({@code @NotBlank}, {@code @NotNull})</li>
     *   <li>Применяется для первичного создания новой записи</li>
     * </ul>
     */
    interface OnCreate {}    // POST - создание.

    /**
     * Группа валидации для операции полного обновления (PUT).
     *
     * <p>Особенности:
     * <ul>
     *   <li>Все поля должны быть заполнены (полная замена)</li>
     *   <li>Применяется для замены всей записи целиком</li>
     * </ul>
     */
    interface OnPut {}       // PUT - полное обновление.

    /**
     * Группа валидации для операции частичного обновления (PATCH).
     *
     * <p>Особенности:
     * <ul>
     *   <li>Поля опциональны — null означает "не обновлять"</li>
     *   <li>Для строковых полей используется {@link NotBlankIfPresent} вместо {@code @NotBlank}</li>
     *   <li>Применяется для частичного обновления записи</li>
     * </ul>
     */
    interface OnPatch {}     // PATCH - частичное обновление.
}